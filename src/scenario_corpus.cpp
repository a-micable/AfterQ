std::size_t scenario_count() {
  return sizeof(kScenarioSpecs) / sizeof(kScenarioSpecs[0]);
}

const ScenarioSpec& scenario_at(std::size_t index) {
  if (index >= scenario_count()) {
    throw std::out_of_range("scenario index out of range");
  }
  return kScenarioSpecs[index];
}

std::vector<uint8_t> build_scenario_manifest(const ScenarioSpec& spec) {
  ManifestWriter writer;
  for (int section_index = 0; section_index < spec.depth; ++section_index) {
    const std::string section = section_index == 0 ? std::string("root") : std::string("section_") + std::to_string(section_index);
    writer.section(section);
    if (section_index + 1 < spec.depth) {
      writer.include(std::string("section_") + std::to_string(section_index + 1));
    }
    for (int field_index = 0; field_index < spec.fields_per_section; ++field_index) {
      const std::string key = std::string("field_") + std::to_string(section_index) + "_" + std::to_string(field_index);
      const int selector = (section_index + field_index + spec.cache_hint) % 4;
      if (selector == 0) {
        writer.field_string(key, std::string(spec.name) + "_value_" + std::to_string(section_index) + "_" + std::to_string(field_index));
      } else if (selector == 1) {
        writer.field_integer(key, static_cast<int64_t>(section_index * 1000 + field_index));
      } else if (selector == 2) {
        writer.field_boolean(key, (field_index % 2) == 0);
      } else {
        writer.field_float_array(key, {static_cast<double>(section_index), static_cast<double>(field_index), static_cast<double>(spec.cache_hint)});
      }
    }
    if (spec.with_dependencies && section_index + 1 < spec.depth) {
      writer.dependency(section, std::string("section_") + std::to_string(section_index + 1));
    }
  }
  if (spec.with_conditionals) {
    ManifestWriter nested;
    nested.section("root");
    nested.field_string("conditional_marker", std::string(spec.name) + "_conditional");
    writer.section("root");
    writer.field_boolean("conditional_enabled", true);
    writer.conditional("conditional_enabled", nested.bytes());
  }
  if (spec.with_schema) {
    InternCache cache(64);
    std::vector<SchemaField> fields;
    fields.push_back({cache.intern("field_0_0"), ValueType::String, false});
    fields.push_back({cache.intern("conditional_enabled"), ValueType::Boolean, false});
    writer.schema("root", fields);
  }
  return writer.bytes();
}

std::vector<uint8_t> build_scenario_manifest(std::size_t index) {
  return build_scenario_manifest(scenario_at(index));
}

std::vector<std::string> scenario_names() {
  std::vector<std::string> names;
  names.reserve(scenario_count());
  for (std::size_t i = 0; i < scenario_count(); ++i) {
    names.push_back(kScenarioSpecs[i].name);
  }
  return names;
}
